// Writes src/engine/voice-durations.ts: how long each voiced line's clip runs (seconds), so the
// story rooms can pace lines on the server without one talking over the next.
// Run after changing public/voice or src/client/voice-lines.ts: node tools/voice-durations.mjs
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("src/client/voice-lines.ts", "utf8");
const out = {};
for (const m of src.matchAll(/^\s*("(?:[^"\\]|\\.)*"):\s*"([^"]+)"/gm)) {
  const key = JSON.parse(m[1]);
  // A time range of a joined file (tools/voice-sprites.py): the clip runs from a to b, less the silence either side.
  const part = /#t=([\d.]+),([\d.]+)$/.exec(m[2]);
  const sec = part ? Number(part[2]) - Number(part[1]) - 0.2 : Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", `public/${m[2]}`]).toString().trim());
  if (sec > 0) out[key] = Math.round(sec * 100) / 100;
}
const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join("\n");
writeFileSync("src/engine/voice-durations.ts", `// Generated by tools/voice-durations.mjs: seconds each voiced line's clip runs, keyed "Who|text".\nexport const VOICE_SECONDS: Record<string, number> = {\n${body}\n};\n`);
console.log(Object.keys(out).length, "lines");
